-- Let the database provision the pg_cron scheduler by itself.
--
-- 0095 schedules the background workers from pg_cron but needed two Vault
-- entries created by hand: the runner secret and the app origin. The
-- runner secret is only known to GitHub and Vercel, where it cannot be
-- read back, so that manual step was the one thing standing between the
-- schedule and a running worker.
--
-- Instead, the database now owns a token of its own:
--
--   * `jobs_runner_secret` in Vault is generated here (256 random bits)
--     when it does not exist yet. pg_cron sends it as the bearer token.
--   * `scheduler_token_valid(token)` lets the app check that bearer token
--     against Vault. Only service_role may call it; the app does so with
--     its admin client, next to the JOBS_RUNNER_SECRET / CRON_SECRET env
--     checks that the GitHub workflow and Vercel Cron keep using.
--   * `app_origin` is the production origin (https://ordilo.de), created
--     only when missing — it is not a secret.
--   * `scheduler_status()` reports the latest cron runs and HTTP responses
--     to service_role, so the schedule can be checked without SQL access.
--
-- Idempotent: secrets are created only when absent, functions are
-- `create or replace`.

create extension if not exists pgcrypto with schema extensions;

do $$
begin
  if not exists (select 1 from vault.secrets where name = 'jobs_runner_secret') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'jobs_runner_secret',
      'Bearer token pg_cron sends to /api/jobs/run and /api/notifications/run (generated by 0096)'
    );
  end if;

  if not exists (select 1 from vault.secrets where name = 'app_origin') then
    perform vault.create_secret(
      'https://ordilo.de',
      'app_origin',
      'Production origin the pg_cron scheduler calls'
    );
  end if;
end;
$$;

-- ---------------------------------------------------------------------------
-- scheduler_token_valid
-- ---------------------------------------------------------------------------

create or replace function public.scheduler_token_valid(p_token text)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(length(p_token), 0) >= 32
    and exists (
      select 1
      from vault.decrypted_secrets
      where name = 'jobs_runner_secret'
        and decrypted_secret = p_token
    );
$$;

revoke execute on function public.scheduler_token_valid(text) from public;
revoke execute on function public.scheduler_token_valid(text) from anon, authenticated;
grant execute on function public.scheduler_token_valid(text) to service_role;

-- ---------------------------------------------------------------------------
-- scheduler_status
-- ---------------------------------------------------------------------------

create or replace function public.scheduler_status()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'jobs', coalesce((
      select jsonb_agg(jsonb_build_object('name', j.jobname, 'schedule', j.schedule, 'active', j.active) order by j.jobname)
      from cron.job j
      where j.jobname like 'ordilo-%'
    ), '[]'::jsonb),
    'runs', coalesce((
      select jsonb_agg(r order by r.start_time desc)
      from (
        select j.jobname, d.status, d.return_message, d.start_time, d.end_time
        from cron.job_run_details d
        join cron.job j on j.jobid = d.jobid
        where j.jobname like 'ordilo-%'
        order by d.start_time desc
        limit 10
      ) r
    ), '[]'::jsonb),
    'responses', coalesce((
      select jsonb_agg(h order by h.created desc)
      from (
        select id, status_code, timed_out, error_msg, left(content, 300) as content, created
        from net._http_response
        order by created desc
        limit 10
      ) h
    ), '[]'::jsonb)
  );
$$;

revoke execute on function public.scheduler_status() from public;
revoke execute on function public.scheduler_status() from anon, authenticated;
grant execute on function public.scheduler_status() to service_role;
